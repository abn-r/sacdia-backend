const loadXlsx = lazyModule(() => require('xlsx') as typeof import('xlsx'));

export const FINANCE_XLSX_CONTENT_TYPE =
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';

export const FINANCE_PDF_CONTENT_TYPE = 'application/pdf';

/** Hard cap of rows in one export so a request cannot exhaust memory. */
export const FINANCE_EXPORT_MAX_ROWS = 20000;
const OVERVIEW_DEFAULT_LIMIT = 100;
const MONTHS_STATUS_CONCURRENCY = 10;

/** Who asked for the export; printed in the PDF «generated by» note. */
export interface FinanceExportRequester {
  userId: string;
  authorization?: AuthorizationSnapshot;
}

export interface FinanceExportFile {
  buffer: Buffer;
  filename: string;
  contentType: string;
  contentDisposition: string;
  /** Only set for formats that must not be cached (PDF). */
  cacheControl?: string;
}

/** Everything both export formats are built from, so they cannot diverge. */
interface FinanceExportData {
  scope: Awaited<ReturnType<FinanceAggregationService['resolveClubScope']>>;
  range: FinanceRange;
  sectionNames: Map<number, string>;
  movements: Array<{
    finance_id: number;
    finance_date: Date;
    club_section_id: number | null;
    amount: number;
    description: string | null;
    post_closing_note: string | null;
    finance_category_id: number;
    finances_categories: { type: number; name: string };
    users: {
      name: string | null;
      paternal_last_name: string | null;
    } | null;
  }>;
  evidenceByFinance: Map<number, number>;
  categoryNames: Map<number, string>;
  totals: FinanceTotals;
}

/**
 * Read-only finance reports built on top of the shared aggregation:
 * by-category breakdown, Excel export and the territorial overview.
 */
@Injectable()
export class FinanceReportsService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly aggregation: FinanceAggregationService,
    private readonly financeScore: FinanceScoreService,
    private readonly authorizationContext: AuthorizationContextService,
    private readonly translationService: TranslationService,
    private readonly sectionResponsibles?: SectionResponsiblesService,
  ) {}

  // ========================================
  // BY CATEGORY (F6)
  // ========================================

  async getByCategory(
    clubId: number,
    query: FinanceReportQueryDto,
    userSectionId?: number | null,
  ) {
    const scope = await this.aggregation.resolveClubScope(
      clubId,
      query.club_section_id,
      userSectionId,
    );
    const range = this.periodRange(query.year, query.month);
    const rows = await this.aggregation.aggregateByCategory(
      scope.sectionIds,
      range,
    );
    const names = await this.translatedCategoryNames(
      rows.map((r) => r.category_id),
    );

    const toItem = (r: (typeof rows)[number]) => ({
      category_id: r.category_id,
      name: names.get(r.category_id) ?? r.name,
      total: r.total,
      count: r.count,
    });
    const income = rows.filter((r) => r.type === 0).map(toItem);
    const expenses = rows.filter((r) => r.type !== 0).map(toItem);

    return {
      club_id: clubId,
      club_section_id: query.club_section_id ?? null,
      period: this.periodLabel(query.year, query.month),
      income,
      expenses,
      totals: {
        income: income.reduce((sum, r) => sum + r.total, 0),
        expenses: expenses.reduce((sum, r) => sum + r.total, 0),
      },
    };
  }

  // ========================================
  // EXCEL EXPORT (F5)
  // ========================================

  async buildExport(
    clubId: number,
    query: FinanceExportQueryDto,
    userSectionId?: number | null,
    requester?: FinanceExportRequester,
  ): Promise<FinanceExportFile> {
    const data = await this.loadExportData(clubId, query, userSectionId);
    if (query.format === 'pdf') {
      return this.buildPdfExport(clubId, query, data, requester);
    }
    return this.buildXlsxExport(query, data);
  }

  /** Single data source of the export, shared by the xlsx and pdf builders. */
  private async loadExportData(
    clubId: number,
    query: FinanceReportQueryDto,
    userSectionId?: number | null,
  ): Promise<FinanceExportData> {
    const scope = await this.aggregation.resolveClubScope(
      clubId,
      query.club_section_id,
      userSectionId,
    );
    const range = this.periodRange(query.year, query.month);
    const sectionNames = new Map(
      scope.sections.map((s) => [s.club_section_id, s.name]),
    );

    const where: Prisma.financesWhereInput = {
      active: true,
      club_section_id: {
        in: scope.sectionIds.length > 0 ? scope.sectionIds : [-1],
      },
      year: query.year,
      ...(query.month ? { month: query.month } : {}),
    };

    const [movements, evidenceCounts, totals] = await Promise.all([
      this.prisma.finances.findMany({
        where,
        select: {
          finance_id: true,
          finance_date: true,
          club_section_id: true,
          amount: true,
          description: true,
          post_closing_note: true,
          finance_category_id: true,
          finances_categories: { select: { type: true, name: true } },
          users: { select: { name: true, paternal_last_name: true } },
        },
        orderBy: [{ finance_date: 'asc' }, { finance_id: 'asc' }],
        take: FINANCE_EXPORT_MAX_ROWS,
      }),
      this.prisma.finance_evidence_files.groupBy({
        by: ['finance_id'],
        where: { active: true, finance: where },
        _count: { _all: true },
      }),
      this.aggregation.aggregate(scope.sectionIds, range),
    ]);

    const evidenceByFinance = new Map(
      evidenceCounts.map((e) => [e.finance_id, e._count._all]),
    );
    const categoryNames = await this.translatedCategoryNames(
      movements.map((m) => m.finance_category_id),
    );

    return {
      scope,
      range,
      sectionNames,
      movements,
      evidenceByFinance,
      categoryNames,
      totals,
    };
  }

  private buildXlsxExport(
    query: FinanceReportQueryDto,
    data: FinanceExportData,
  ): FinanceExportFile {
    const {
      scope,
      sectionNames,
      movements,
      evidenceByFinance,
      categoryNames,
      totals,
    } = data;

    const XLSX = loadXlsx();
    const wb = XLSX.utils.book_new();

    const header = [
      'Fecha',
      'Sección',
      'Tipo',
      'Categoría',
      'Descripción',
      'Monto',
      'Registró',
      'Evidencias',
      'Nota de cierre',
    ];
    const rows = movements.map((m) => [
      m.finance_date.toISOString().slice(0, 10),
      m.club_section_id != null
        ? (sectionNames.get(m.club_section_id) ?? '')
        : '',
      m.finances_categories.type === 0 ? 'Ingreso' : 'Egreso',
      categoryNames.get(m.finance_category_id) ?? m.finances_categories.name,
      m.description ?? '',
      m.amount,
      m.users ? `${m.users.name} ${m.users.paternal_last_name}`.trim() : '',
      evidenceByFinance.get(m.finance_id) ?? 0,
      m.post_closing_note ?? '',
    ]);
    const movementsSheet = XLSX.utils.aoa_to_sheet([header, ...rows]);
    movementsSheet['!cols'] = [
      { wch: 12 },
      { wch: 16 },
      { wch: 9 },
      { wch: 24 },
      { wch: 40 },
      { wch: 12 },
      { wch: 24 },
      { wch: 11 },
      { wch: 40 },
    ];
    XLSX.utils.book_append_sheet(wb, movementsSheet, 'Movimientos');

    const sectionLabel =
      scope.sections.length === 1
        ? scope.sections[0].name
        : scope.sections.map((s) => s.name).join(', ');
    const summarySheet = XLSX.utils.aoa_to_sheet(
      this.summaryRows(
        scope.club.name,
        sectionLabel,
        this.periodLabel(query.year, query.month),
        totals,
      ),
    );
    summarySheet['!cols'] = [{ wch: 20 }, { wch: 28 }];
    XLSX.utils.book_append_sheet(wb, summarySheet, 'Resumen');

    const buffer = XLSX.write(wb, {
      type: 'buffer',
      bookType: 'xlsx',
    }) as Buffer;

    const filename = `finanzas-${slugMonthlyReportNamePart(
      scope.club.name,
      'club',
    )}-${this.periodLabel(query.year, query.month)}.xlsx`;

    return {
      buffer,
      filename,
      contentType: FINANCE_XLSX_CONTENT_TYPE,
      contentDisposition: monthlyReportContentDisposition(filename),
    };
  }

  private async buildPdfExport(
    clubId: number,
    query: FinanceReportQueryDto,
    data: FinanceExportData,
    requester?: FinanceExportRequester,
  ): Promise<FinanceExportFile> {
    const { scope, range, sectionNames, movements, categoryNames, totals } =
      data;

    const [categoryRows, closing, localFieldName, responsibles, generatedBy] =
      await Promise.all([
        this.aggregation.aggregateByCategory(scope.sectionIds, range),
        query.month
          ? this.prisma.financePeriodClosing.findUnique({
              where: {
                club_id_year_month: {
                  club_id: clubId,
                  year: query.year,
                  month: query.month,
                },
              },
              select: { finance_period_closing_id: true, closed_at: true },
            })
          : Promise.resolve(null),
        this.clubLocalFieldName(clubId),
        this.sectionResponsibles
          ? this.sectionResponsibles.forSections(clubId, scope.sectionIds)
          : Promise.resolve(new Map()),
        this.generatedByOf(clubId, requester),
      ]);
    const names = await this.translatedCategoryNames(
      categoryRows.map((r) => r.category_id),
    );
    const toRow = (
      r: (typeof categoryRows)[number],
    ): FinancePdfCategoryRow => ({
      name: names.get(r.category_id) ?? r.name,
      count: r.count,
      total: r.total,
    });

    const sectionFiltered = query.club_section_id != null;
    const sectionLabel = sectionFiltered
      ? scope.sections.map((s) => s.name).join(', ')
      : 'Todas las secciones';

    const buffer = await renderFinanceExportPdf({
      clubName: scope.club.name,
      localFieldName,
      sectionLabel,
      sectionFiltered,
      year: query.year,
      month: query.month,
      periodLabel: pdfPeriodLabel(query.year, query.month),
      generatedAt: new Date(),
      monthClosed: closing != null,
      closedAt: closing?.closed_at ?? null,
      generatedBy,
      responsibles: scope.sections.map((s) => ({
        sectionName: s.name,
        director: responsibles.get(s.club_section_id)?.director ?? null,
        treasurer: responsibles.get(s.club_section_id)?.treasurer ?? null,
      })),
      totals,
      income: categoryRows.filter((r) => r.type === 0).map(toRow),
      expenses: categoryRows.filter((r) => r.type !== 0).map(toRow),
      movements: movements.map((m) => ({
        date: m.finance_date,
        sectionName:
          m.club_section_id != null
            ? (sectionNames.get(m.club_section_id) ?? '')
            : '',
        type: m.finances_categories.type,
        category:
          categoryNames.get(m.finance_category_id) ??
          m.finances_categories.name,
        description: m.description ?? '',
        amount: m.amount,
        closingNote: m.post_closing_note ?? '',
      })),
    });

    const filename = `finanzas-${slugMonthlyReportNamePart(
      scope.club.name,
      'club',
    )}-${this.periodLabel(query.year, query.month)}.pdf`;

    return {
      buffer,
      filename,
      contentType: FINANCE_PDF_CONTENT_TYPE,
      contentDisposition: monthlyReportContentDisposition(filename),
      cacheControl: 'no-store',
    };
  }

  private async clubLocalFieldName(clubId: number): Promise<string | null> {
    const club = await this.prisma.clubs.findUnique({
      where: { club_id: clubId },
      select: { local_fields: { select: { name: true } } },
    });
    return club?.local_fields?.name ?? null;
  }

  /** Requesting user's «Nombre Apellido» and the role they act with. */
  private async generatedByOf(
    clubId: number,
    requester?: FinanceExportRequester,
  ): Promise<{ name: string; roleLabel: string | null } | null> {
    if (!requester) return null;
    const user = await this.prisma.users.findUnique({
      where: { user_id: requester.userId },
      select: { name: true, paternal_last_name: true },
    });
    const name = [user?.name, user?.paternal_last_name]
      .filter(Boolean)
      .join(' ')
      .trim();
    if (!name) return null;
    return {
      name,
      roleLabel: requesterRoleLabel(requester.authorization, clubId),
    };
  }

  private summaryRows(
    clubName: string,
    sectionLabel: string,
    period: string,
    totals: FinanceTotals,
  ): Array<Array<string | number>> {
    return [
      ['Concepto', 'Valor'],
      ['Club', clubName],
      ['Sección', sectionLabel],
      ['Periodo', period],
      ['Ingresos', totals.income],
      ['Egresos', totals.expenses],
      ['Neto', totals.net],
      ['Saldo acumulado', totals.balance],
      ['Movimientos', totals.movements],
    ];
  }

  // ========================================
  // OVERVIEW FOR LOCAL FIELD / UNION / DIVISION (F7)
  // ========================================

  /**
   * Finance of every club in the caller's territory.
   *
   * Authorization: the route requires `finances:read` on a `global` resource;
   * here the caller must hold a NON-base global role that carries it
   * (admin, assistant-admin, Local Field, union, division) and the clubs are
   * limited to its territory. A club-level treasurer has no global grant and
   * gets 403.
   */
  async getOverview(actorId: string, query: FinanceOverviewQueryDto) {
    const resolved =
      await this.authorizationContext.resolveUserAuthorization(actorId);

    if (!actorHasGlobalPermission(resolved, 'finances:read')) {
      throw new AppForbiddenException(ErrorCode.GUARD_PERMISSION_DENIED);
    }

    const territory = resolveActorTerritoryScope(resolved);
    if (territory.level === 'open') {
      throw new AppForbiddenException(ErrorCode.GUARD_PERMISSION_DENIED);
    }
    // 'unconfigured' makes clubsWhereForActor throw ADMIN_USER_SCOPE_MISSING.
    const scopeWhere: Prisma.clubsWhereInput =
      territory.level === 'all' ? {} : clubsWhereForActor(territory);

    const year = query.year ?? new Date().getUTCFullYear();
    const page = query.page ?? 1;
    const limit = Math.min(query.limit ?? OVERVIEW_DEFAULT_LIMIT, 100);
    const range = this.periodRange(year, query.month);

    const clubs = await this.prisma.clubs.findMany({
      where: {
        active: true,
        AND: [
          scopeWhere,
          ...(query.local_field_id != null
            ? [{ local_field_id: query.local_field_id }]
            : []),
        ],
      },
      select: {
        club_id: true,
        name: true,
        local_fields: { select: { local_field_id: true, name: true } },
      },
      orderBy: [{ name: 'asc' }, { club_id: 'asc' }],
    });

    const totalsByClub = await this.aggregation.aggregateByClub(
      clubs.map((c) => c.club_id),
      range,
    );

    const grand = { income: 0, expenses: 0, net: 0, balance: 0, movements: 0 };
    for (const t of totalsByClub.values()) {
      grand.income += t.income;
      grand.expenses += t.expenses;
      grand.net += t.net;
      grand.balance += t.balance;
      grand.movements += t.movements;
    }

    const pageClubs = clubs.slice((page - 1) * limit, page * limit);
    const monthsStatus = new Map<number, number[]>();
    for (let i = 0; i < pageClubs.length; i += MONTHS_STATUS_CONCURRENCY) {
      const chunk = pageClubs.slice(i, i + MONTHS_STATUS_CONCURRENCY);
      const results = await Promise.all(
        chunk.map((c) => this.financeScore.getMonthsStatus(c.club_id, year)),
      );
      chunk.forEach((c, idx) =>
        monthsStatus.set(c.club_id, results[idx].missedMonths),
      );
    }

    const data = pageClubs.map((club) => {
      const t = totalsByClub.get(club.club_id);
      const missed = monthsStatus.get(club.club_id) ?? [];
      return {
        club_id: club.club_id,
        club_name: club.name,
        local_field: club.local_fields
          ? {
              local_field_id: club.local_fields.local_field_id,
              name: club.local_fields.name,
            }
          : null,
        income: t?.income ?? 0,
        expenses: t?.expenses ?? 0,
        net: t?.net ?? 0,
        balance: t?.balance ?? 0,
        movements: t?.movements ?? 0,
        months_without_movements: missed.length,
        missed_months: missed,
        last_movement_at: t?.last_movement_at ?? null,
      };
    });

    return {
      period: this.periodLabel(year, query.month),
      data,
      totals: grand,
      meta: {
        page,
        limit,
        total: clubs.length,
        totalPages: Math.ceil(clubs.length / limit),
      },
    };
  }

  // ========================================
  // HELPERS
  // ========================================

  private periodRange(year: number, month?: number): FinanceRange {
    return month
      ? { from: { year, month }, to: { year, month } }
      : { from: { year, month: 1 }, to: { year, month: 12 } };
  }

  /** `2026` for a whole year, `2026-03` for a month. */
  private periodLabel(year: number, month?: number): string {
    return month ? `${year}-${String(month).padStart(2, '0')}` : String(year);
  }

  private async translatedCategoryNames(
    categoryIds: number[],
  ): Promise<Map<number, string>> {
    const ids = [...new Set(categoryIds)];
    const names = new Map<number, string>();
    if (ids.length === 0) return names;

    const locale = this.translationService.getCurrentLocale();
    const records = await this.prisma.finances_categories.findMany({
      where: { finance_category_id: { in: ids } },
      select: {
        finance_category_id: true,
        name: true,
        translations: {
          where: { locale },
          select: { locale: true, name: true, description: true },
        },
      },
    });
    const translated = this.translationService.translateMany(
      records,
      locale,
      ['name'],
      'translations',
    );
    for (const r of translated) names.set(r.finance_category_id, r.name);
    return names;
  }
}
